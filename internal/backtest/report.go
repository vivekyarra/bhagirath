// Run replays every outbreak under both scenarios and every variant.
func Run(r *rule.Rule, obs []Outbreak, vs []Variant, ladderHours map[domain.Level]int) []Result {
	var out []Result
	for _, o := range obs {
		variants := append([]Variant{{Slug: o.Slug, Name: "All rows about the affected area"}}, filterVariants(vs, o.Slug)...)
		for _, v := range variants {
			rows := Filter(o.Rows, v)
			for _, s := range []Scenario{Best, Conservative} {
				res := Replay(r, o, rows, s, ladderHours)
				res.Variant = v.Name
				out = append(out, res)
			}
		}
	}
	return out
}

func filterVariants(vs []Variant, slug string) []Variant {
	var out []Variant
	for _, v := range vs {
		if v.Slug == slug {
			out = append(out, v)
		}
	}
	return out
}

func d(t time.Time) string {
	if t.IsZero() {
		return "never"
	}
	return t.In(clock.IST).Format("2 Jan 2006")
}

// lead returns "N days before" / "N days after" relative to ref.
func lead(t time.Time, ref string) string {
	if t.IsZero() {
		return "—"
	}
	r, err := date(ref)
	if err != nil || r.IsZero() {
		return "n/a (date unknown)"
	}
	days := r.Sub(t).Hours() / 24
	switch {
	case math.Abs(days) < 1:
		return "same day"
	case days > 0:
		return fmt.Sprintf("**%.0f days before**", math.Floor(days))
	}
	return fmt.Sprintf("%.0f days after", math.Ceil(-days))
}

// Markdown renders RESULTS.md. It is generated, deterministic and checked in;
// CI regenerates it and fails if it differs.
func Markdown(r *rule.Rule, obs []Outbreak, vs []Variant, results []Result) string {
	var b strings.Builder
	b.WriteString("# Backtest results (generated)\n\n")
	fmt.Fprintf(&b, "Generated by `bhagirath backtest` from `backtest/data/*.csv` with alert rule **%s** (SHA-256 `%s`), the file frozen at git tag `%s` before any timeline was collected. Do not edit by hand; CI regenerates this file and fails if it changes.\n\n", r.Version, r.SHA256, rule.FrozenTag)
	b.WriteString("- **best**: each row placed from its earliest plausible date, counts spread evenly across its date range.\n- **conservative**: every row placed at its latest plausible date (undated rows at their publication date).\n- \"Commissioner by\" assumes nobody acknowledges anything and follows the escalation ladder (Watch → rung 1, then 72 h timeouts to rungs 2 and 3; Warning → rungs 1, 2 and health with a 48 h deadline; Critical → every rung).\n\n")
	for _, o := range obs {
		fmt.Fprintf(&b, "## %s (%s)\n\n", o.Name, o.Period)
		fmt.Fprintf(&b, "First hospitalisation: %s%s. First death: %s%s. Deaths reported: %s.\n\n", orUnknown(o.FirstHospitalisation), alt(o.FirstHospOfficial, "official"), orUnknown(o.FirstDeath), alt(o.FirstDeathCorroborated, "corroborated"), o.DeathsReported)
		b.WriteString("| Variant | Scenario | Inputs (complaints / tests / illness reports) | First Watch | First Warning or higher | First Critical | Commissioner by | Watch vs first death | Watch vs first corroborated death |\n|---|---|---|---|---|---|---|---|---|\n")
		var firstWatch []string
		for _, res := range results {
			if res.Slug != o.Slug {
				continue
			}
			fmt.Fprintf(&b, "| %s | %s | %d / %d / %d | %s | %s | %s | %s | %s | %s |\n", res.Variant, res.Scenario, res.Inputs.Complaints, res.Inputs.Tests, res.Inputs.Illness,
				d(res.FirstAt[domain.LevelWatch]), d(res.FirstAt[domain.LevelWarning]), d(res.FirstAt[domain.LevelCritical]), d(res.CommissionerBy),
				lead(res.FirstAt[domain.LevelWatch], o.FirstDeath), lead(res.FirstAt[domain.LevelWatch], o.FirstDeathCorroborated))
			if res.Variant == "All rows about the affected area" {
				firstWatch = append(firstWatch, fmt.Sprintf("- *%s*: first Watch reason — %s", res.Scenario, orNone(res.ReasonAt[domain.LevelWatch])),
					fmt.Sprintf("- *%s*: first Warning-or-higher reason — %s", res.Scenario, orNone(res.ReasonAt[domain.LevelWarning])))
			}
		}
		b.WriteString("\n" + strings.Join(firstWatch, "\n") + "\n\n")
		for _, v := range vs {
			if v.Slug == o.Slug {
				fmt.Fprintf(&b, "> Variant \"%s\": %s\n\n", v.Name, v.Why)
			}
		}
		fmt.Fprintf(&b, "Data quality: %s\n\n", o.DataQuality)
	}
	return b.String()
}

func orUnknown(s string) string {
	if s == "" || s == "null" {
		return "not found"
	}
	return s
}

func alt(s, label string) string {
	if s == "" {
		return ""
	}
	return fmt.Sprintf(" (%s: %s)", label, s)
}

func orNone(s string) string {
	if s == "" {
		return "never reached"
	}
	return "“" + s + "”"
}

// JSON renders machine-readable results.
func JSON(results []Result) ([]byte, error) {
	type out struct {
		Slug, Name, Variant, Scenario, Rule, RuleSHA256  string
		FirstWatch, FirstWarning, FirstCritical          string
		FirstC, FirstT, FirstI, CommissionerBy, HealthBy string
		Inputs                                           any
	}
	f := func(t time.Time) string {
		if t.IsZero() {
			return ""
		}
		return t.Format(time.RFC3339)
	}
	var xs []out
	for _, r := range results {
		xs = append(xs, out{r.Slug, r.Name, r.Variant, string(r.Scenario), r.RuleVersion, r.RuleSHA256,
			f(r.FirstAt[domain.LevelWatch]), f(r.FirstAt[domain.LevelWarning]), f(r.FirstAt[domain.LevelCritical]),
			f(r.FirstSignal["C"]), f(r.FirstSignal["T"]), f(r.FirstSignal["I"]), f(r.CommissionerBy), f(r.HealthOfficerBy), r.Inputs})
	}
	return json.MarshalIndent(xs, "", "  ")
}
