// Package metrics renders the pilot impact report (pilot/METRICS.md) and
// compares it with the winning-grade targets of spec Section 3.2. Numbers
// come only from store.ComputeMetrics; nothing is typed in by hand.
package metrics

import (
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/vivekyarra/bhagirath/internal/asr"
	"github.com/vivekyarra/bhagirath/internal/clock"
	"github.com/vivekyarra/bhagirath/internal/store"
)

// Target is one row of the Section 3.2 table.
type Target struct {
	Metric  string
	Actual  string
	Target  string
	Stretch string
	Met     *bool // nil when the metric is not a simple threshold
}

func b(v bool) *bool { return &v }

func pct(n, d int) string {
	if d == 0 {
		return "n/a (0 eligible)"
	}
	return fmt.Sprintf("%.0f%% (%d/%d)", 100*float64(n)/float64(d), n, d)
}

func atLeast(name string, actual, target, stretch int) Target {
	return Target{Metric: name, Actual: fmt.Sprint(actual), Target: fmt.Sprintf("%d+", target), Stretch: fmt.Sprintf("%d+", stretch), Met: b(actual >= target)}
}

func f1(p *float64) string {
	if p == nil {
		return "n/a"
	}
	return fmt.Sprintf("%.1f", *p)
}

// Targets evaluates Section 3.2 against measured metrics.
func Targets(m store.Metrics, asrRecordings int, asrWER *float64) []Target {
	ackRate := 0.0
	if m.EscalationsDecided > 0 {
		ackRate = float64(m.EscalationsAcked) / float64(m.EscalationsDecided)
	}
	langs := 0
	for k, n := range m.Languages {
		if k != "unknown" && n > 0 {
			langs++
		}
	}
	ts := []Target{
		atLeast("Pilot wards / villages", m.Wards, 2, 3),
		atLeast("Households informed about Bhagirath", m.HouseholdsInformed, 500, 1000),
		atLeast("Real complaints logged through Bhagirath", m.Complaints, 50, 100),
		atLeast("Complaints from non-smartphone channels (missed call / IVR / volunteer line)", m.NonSmartphone, 20, 40),
		atLeast("Distinct reporters", m.DistinctReporters, 30, 60),
		{Metric: "Eligible complaints escalated (each with an evidence pack)", Actual: pct(m.EscalatedComplaints, m.EligibleComplaints), Target: "100%", Stretch: "—",
			Met: b(m.EligibleComplaints > 0 && m.EscalatedComplaints >= m.EligibleComplaints)},
		{Metric: "Escalations acknowledged by an official", Actual: pct(m.EscalationsAcked, m.EscalationsDecided), Target: "50%+", Stretch: "75%+", Met: b(m.EscalationsDecided > 0 && ackRate >= 0.5)},
		atLeast("Complaints closed with verified evidence (evidence + complainant confirmation)", m.VerifiedClosures, 15, 30),
		{Metric: "False/premature closures caught and reopened", Actual: fmt.Sprintf("%d (denied %d, no answer %d)", m.ReopenedComplaints, m.ClosuresDenied, m.ClosuresNoAnswer),
			Target: "every one caught and logged", Stretch: "—"},
		{Metric: "Median days to verified fix — pilot vs baseline", Actual: fmt.Sprintf("%s vs %s (baseline n=%d)", f1(m.MedianDaysToFix), f1(m.BaselineMedianDays), m.BaselineSamples),
			Target: "clear measured improvement", Stretch: "2x faster", Met: improvement(m)},
		atLeast("Clinics / chemists / ASHAs contributing illness signals", m.IllnessContributors, 5, 10),
		{Metric: "Advisories delivered to affected registered households", Actual: pct(m.AdvisoriesDelivered, m.AdvisoriesSent), Target: "100%", Stretch: "—",
			Met: b(m.AdvisoriesSent > 0 && m.AdvisoriesDelivered == m.AdvisoriesSent)},
		atLeast("Languages seen in real complaints", langs, 3, 4),
		{Metric: "Recordings with measured speech-recognition error", Actual: fmt.Sprintf("%d (WER %s)", asrRecordings, pctPtr(asrWER)), Target: "50+", Stretch: "100+", Met: b(asrRecordings >= 50)},
		atLeast("Pilot days with recorded activity", m.ActiveDays, 10, 14),
	}
	return ts
}

func pctPtr(p *float64) string {
	if p == nil {
		return "n/a"
	}
	return fmt.Sprintf("%.1f%%", 100**p)
}

func improvement(m store.Metrics) *bool {
	if m.MedianDaysToFix == nil || m.BaselineMedianDays == nil || m.BaselineSamples == 0 {
		return nil
	}
	return b(*m.MedianDaysToFix < *m.BaselineMedianDays)
}

// Markdown renders METRICS.md.
func Markdown(m store.Metrics, ts []Target, deployment string) string {
	var w strings.Builder
	ist := m.GeneratedAt.In(clock.IST)
	fmt.Fprintf(&w, "# Bhagirath — Pilot Metrics\n\n")
	fmt.Fprintf(&w, "**Exported from the database:** %s (%s)  \n", ist.Format("2 Jan 2006, 15:04 IST"), m.GeneratedAt.Format(time.RFC3339))
	fmt.Fprintf(&w, "**Deployment:** %s  \n", deployment)
	if m.FirstEvent != nil && m.LastEvent != nil {
		fmt.Fprintf(&w, "**Data window:** %s → %s (%d active days)\n\n", m.FirstEvent.In(clock.IST).Format("2 Jan 2006"), m.LastEvent.In(clock.IST).Format("2 Jan 2006"), m.ActiveDays)
	} else {
		w.WriteString("**Data window:** no pilot activity recorded yet\n\n")
	}
	w.WriteString("Generated by `bhagirath export-metrics`. Every number below is a database query (see `internal/store/metrics.go`); nothing is hand-counted or rounded up. Demo wards are excluded.\n\n")
	w.WriteString("## Winning-grade targets (spec §3.2)\n\n| Metric | Actual | Target | Stretch | Status |\n|---|---|---|---|---|\n")
	for _, t := range ts {
		st := "—"
		if t.Met != nil {
			st = map[bool]string{true: "✅ met", false: "⬜ below target"}[*t.Met]
		}
		fmt.Fprintf(&w, "| %s | %s | %s | %s | %s |\n", t.Metric, t.Actual, t.Target, t.Stretch, st)
	}
	w.WriteString("\n## Reach\n\n")
	fmt.Fprintf(&w, "- Households informed (outreach log): **%d**\n- Registered households: **%d** (consented to callbacks: %d)\n- Pilot wards/villages: **%d**\n", m.HouseholdsInformed, m.RegisteredHouseholds, m.ConsentedHouseholds, m.Wards)
	w.WriteString("\n## Complaints\n\n")
	fmt.Fprintf(&w, "- Unique complaints: **%d** (same-household repeats linked as duplicates: %d; anonymous: %d)\n", m.Complaints, m.Duplicates, m.AnonymousComplaints)
	fmt.Fprintf(&w, "- From non-smartphone channels: **%d**\n- Distinct reporters: **%d**\n- Resolved to a ward: **%s**; follow-up questions asked: %d; ward corrections by volunteers: %d\n",
		m.NonSmartphone, m.DistinctReporters, pct(m.Located, m.Complaints), m.FollowupsAsked, m.WardCorrections)
	fmt.Fprintf(&w, "- By channel: %s\n- By issue: %s\n- By status: %s\n- Languages: %s\n", kv(m.ComplaintsByChannel), kv(m.ComplaintsByIssue), kv(m.ComplaintsByStatus), kv(m.Languages))
	w.WriteString("\n## Alerts and escalations\n\n")
	fmt.Fprintf(&w, "- Alerts by peak level: %s (active now: %d)\n", kv(m.AlertsByPeak), m.AlertsActive)
	fmt.Fprintf(&w, "- Escalations sent: **%d**; acknowledged: **%d**; timed out and auto-escalated: **%d**; grievance numbers tracked: %d\n", m.EscalationsSent, m.EscalationsAcked, m.EscalationsTimedOut, m.GrievanceNumbers)
	fmt.Fprintf(&w, "- Median hours to acknowledgement: %s\n", f1(m.MedianHoursToAck))
	w.WriteString("\n## Closures (the accountability loop)\n\n")
	fmt.Fprintf(&w, "- Fix claims: **%d**; verified (evidence + complainant confirmed): **%d**\n- Claims rejected by the complainant: **%d**; unanswered after 3 attempts: **%d**; complaints reopened: **%d**\n",
		m.ClosureClaims, m.VerifiedClosures, m.ClosuresDenied, m.ClosuresNoAnswer, m.ReopenedComplaints)
	fmt.Fprintf(&w, "- Median days from complaint to verified fix: **%s** vs baseline **%s** (n=%d observations, %d never fixed; never-fixed cases are counted at the days observed, which understates the baseline)\n",
		f1(m.MedianDaysToFix), f1(m.BaselineMedianDays), m.BaselineSamples, m.BaselineUnresolved)
	w.WriteString("\n## Signals and advisories\n\n")
	fmt.Fprintf(&w, "- Water tests: %d (failed: %d)\n- Illness reports: %d from %d contributing clinics/chemists/ASHAs (%d registered)\n- Advisories sent: %d to %d households; delivered: %d\n",
		m.WaterTests, m.WaterTestsFailed, m.IllnessReports, m.IllnessContributors, m.SignalReporters, m.AdvisoriesSent, m.AdvisoryHouseholdsTargeted, m.AdvisoriesDelivered)
	fmt.Fprintf(&w, "- Outbound messages by status: %s\n", kv(m.MessagesByStatus))
	w.WriteString("\n## Honesty notes\n\n- Below-target numbers are reported as they are. The only acceptable reason for a shortfall is that the calendar ran out while the pilot was still running.\n- \"Delivered\" means the provider confirmed delivery; \"simulated\" messages (demo mode) are never counted as delivered in pilot exports.\n")
	return w.String()
}

func kv(m map[string]int) string {
	if len(m) == 0 {
		return "none"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = fmt.Sprintf("%s %d", strings.ReplaceAll(k, "_", " "), m[k])
	}
	return strings.Join(parts, ", ")
}

// ASRMarkdown renders the speech-recognition section of METRICS.md.
func ASRMarkdown(n int, agg *asr.ErrorRates, langs []LanguageRates) string {
	var w strings.Builder
	w.WriteString("\n## Speech recognition (machine vs volunteer-corrected transcripts)\n\n")
	if n == 0 || agg == nil {
		w.WriteString("No recordings with both a machine and a human transcript yet.\n")
		return w.String()
	}
	fmt.Fprintf(&w, "Measured on **%d** recordings: WER **%.1f%%**, CER **%.1f%%** (pooled).\n\n| Language | Recordings | WER | CER |\n|---|---|---|---|\n", n, 100*agg.WER, 100*agg.CER)
	for _, l := range langs {
		fmt.Fprintf(&w, "| %s | %d | %.1f%% | %.1f%% |\n", l.Lang, l.N, 100*l.Rates.WER, 100*l.Rates.CER)
	}
	return w.String()
}
